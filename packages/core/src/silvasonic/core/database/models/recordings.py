import uuid
from datetime import UTC, datetime
from typing import Any

from silvasonic.core.database.models.base import Base
from sqlalchemy import BigInteger, Boolean, DateTime, Float, ForeignKey, Integer, Text, Uuid, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column


class Recording(Base):
    """Registry of all audio files recorded by the system.

    Standard PostgreSQL table (ADR-0025). FK constraints from ``detections``
    and ``uploads`` are preserved. Data volume (~2M rows/year) does not
    require Hypertable partitioning.
    """

    __tablename__ = "recordings"

    # UUIDv7 generated by the database (ADR-0033)
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, server_default=text("uuidv7()"))

    # Wall-clock time of the first sample; indexed but not part of the PK
    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )

    microphone_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("microphones.id"), nullable=False, index=True
    )

    raw_path: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    processed_path: Mapped[str | None] = mapped_column(Text, nullable=True, index=True)

    duration_s: Mapped[float] = mapped_column(Float, nullable=False)
    # Native rate of the microphone (raw stream), not of the indexed file
    sample_rate_hz: Mapped[int] = mapped_column(Integer, nullable=False)
    channels: Mapped[int] = mapped_column(
        Integer, default=1, server_default=text("1"), nullable=False
    )

    raw_size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    processed_size_bytes: Mapped[int] = mapped_column(BigInteger, default=0, nullable=False)

    uploaded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    # Soft delete: set when the local audio is removed (``retention`` | ``missing``)
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    deletion_reason: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Analysis status map — Worker Pull (ADR-0018). Each value follows
    # ``silvasonic.core.schemas.analysis.AnalysisState``.
    analysis_state: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        default=dict,
        server_default=text("'{}'::jsonb"),
        nullable=False,
    )

    # False: named while the system clock was unsynchronised, ``started_at`` may be off
    # (Issue 002)
    clock_synced: Mapped[bool] = mapped_column(
        Boolean, default=True, server_default=text("true"), nullable=False
    )


class Upload(Base):
    """Immutable audit log of all upload attempts."""

    __tablename__ = "uploads"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, server_default=text("uuidv7()"))

    recording_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("recordings.id"), nullable=False, index=True
    )

    attempted_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC), nullable=False
    )
    filename: Mapped[str] = mapped_column(Text, nullable=False)
    remote_path: Mapped[str | None] = mapped_column(Text, nullable=True)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)

    success: Mapped[bool] = mapped_column(Boolean, nullable=False)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)
